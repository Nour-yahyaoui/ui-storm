/**
 * Bundles `dist/esm` into one classic script that sets `globalThis.bidiKit`.
 *
 * `<script type="module">` works in every current browser, but it needs a
 * server, a bundler or a copy of the `dist/esm` tree: module files cannot be
 * loaded from `file://`, and `import` from a CDN only helps once the package is
 * published. The single file this produces works when the page is opened by
 * double-clicking it, in a `<script>` tag, in a CMS "custom HTML" box, and in
 * `require()` from Node.
 *
 * The source modules are small, acyclic and written in one style, so the bundle
 * is produced by resolving their relative imports in dependency order rather
 * than by adding a bundler to the project. `tests/global.test.mjs` holds the
 * result to the same behaviour as the ES module build, and this script refuses
 * to emit anything if two modules would share a top-level name.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const esm = join(root, "dist", "esm");
const entry = "index.js";

const IMPORT = /^import\s*(?:\{[^}]*\}|\*\s*as\s*\w+|\w+)\s*from\s*"\.\/([^"]+)";?$/gm;
const REEXPORT = /^export\s*\{([^}]*)\}\s*from\s*"\.\/([^"]+)";?$/gm;
const DECLARED = /^(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm;

const read = (file) => readFileSync(join(esm, file), "utf8");

/** Both `import … from "./x.js"` and `export … from "./x.js"` are edges. */
function dependencies(file) {
  const source = read(file);
  const found = [
    ...[...source.matchAll(IMPORT)].map((match) => match[1]),
    ...[...source.matchAll(REEXPORT)].map((match) => match[2]),
  ];
  return found.filter((specifier) => typeof specifier === "string" && specifier.length > 0);
}

/** Depth-first dependency order: a module is emitted after everything it imports. */
function order(entryFile) {
  const sorted = [];
  const seen = new Set();
  const stack = new Set();
  const visit = (file) => {
    if (seen.has(file)) return;
    if (stack.has(file)) throw new Error(`circular import at ${file}`);
    stack.add(file);
    for (const dependency of dependencies(file)) visit(dependency);
    stack.delete(file);
    seen.add(file);
    sorted.push(file);
  };
  visit(entryFile);
  return sorted;
}

/** Drops the module syntax, keeping the declarations in a shared scope. */
function strip(file) {
  let source = read(file);
  source = source.replace(REEXPORT, "");
  source = source.replace(IMPORT, "");
  source = source.replace(/^export\s+(?=(?:const|let|var|function|class|async))/gm, "");
  source = source.replace(/^export\s*\{\s*\};?$/gm, "");
  return source.trim();
}

function exportedNames(file) {
  const names = [];
  for (const match of read(file).matchAll(REEXPORT)) {
    names.push(...(match[1] ?? "").split(",").map((name) => name.trim()).filter(Boolean));
  }
  for (const match of read(file).matchAll(
    /^export\s+(?:const|let|var|function|class|async function)\s+([A-Za-z_$][\w$]*)/gm,
  )) {
    names.push(match[1]);
  }
  return names;
}

const files = order(entry);
const names = exportedNames(entry);
if (names.length === 0) throw new Error("the entry module exports nothing");

const declarations = new Map();
for (const file of files) {
  for (const match of strip(file).matchAll(DECLARED)) {
    const name = match[1];
    const owner = declarations.get(name);
    if (owner) throw new Error(`"${name}" is declared in both ${owner} and ${file}; rename one of them`);
    declarations.set(name, file);
  }
}

const missing = names.filter((name) => !declarations.has(name));
if (missing.length > 0) throw new Error(`exported but never declared: ${missing.join(", ")}`);

const version = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version;
// Modules are emitted at column 0, never re-indented: a template literal holds
// the stylesheet, and shifting its lines would change the value.
const body = files
  .map((file) => `// ---- ${file} ${"-".repeat(Math.max(1, 66 - file.length))}\n${strip(file)}`)
  .join("\n\n");

const bundle = `/*! bidi-kit v${version} — MIT — generated by scripts/build-global.mjs, do not edit.
 *  Arabic inside English, French inside Arabic. https://github.com/Nour-yahyaoui/ui-storm */
(function (root, factory) {
  if (typeof module === "object" && module.exports) module.exports = factory();
  else root.bidiKit = factory();
})(typeof globalThis !== "undefined" ? globalThis : this, function () {
  "use strict";

${body}

  return { ${names.join(", ")} };
});
`;

const target = join(root, "dist", "bidi-kit.global.js");
writeFileSync(target, bundle);
const bytes = Buffer.byteLength(bundle);
console.log(`wrote dist/bidi-kit.global.js — ${names.length} exports, ${(bytes / 1024).toFixed(1)} kB`);
